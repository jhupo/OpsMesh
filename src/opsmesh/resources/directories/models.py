"""Persistent directory registrations and explicit user grants; files remain on disk."""

from uuid import UUID

from sqlalchemy import Boolean, CheckConstraint, ForeignKey, Index, String, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from opsmesh.shared.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin

DIRECTORY_ACTIVE = "active"
DIRECTORY_DELETED = "deleted"
DIRECTORY_PERMISSIONS = frozenset({"read", "write", "use"})


class ResourceDirectory(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """One persistent root; its storage key is generated by the server."""

    __tablename__ = "resource_directories"
    __table_args__ = (
        CheckConstraint("status IN ('active', 'deleted')", name="directory_status"),
        Index(
            "uq_resource_default_directory",
            "owner_user_id",
            unique=True,
            postgresql_where=text("is_default AND status = 'active'"),
        ),
    )

    owner_user_id: Mapped[UUID] = mapped_column(ForeignKey("users.id"), index=True)
    name: Mapped[str] = mapped_column(String(200), nullable=False)
    storage_key: Mapped[str] = mapped_column(String(100), unique=True, nullable=False)
    status: Mapped[str] = mapped_column(String(16), default=DIRECTORY_ACTIVE, nullable=False)
    is_default: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)


class DirectoryGrant(TimestampMixin, Base):
    __tablename__ = "resource_directory_grants"

    directory_id: Mapped[UUID] = mapped_column(
        ForeignKey("resource_directories.id", ondelete="CASCADE"), primary_key=True
    )
    grantee_user_id: Mapped[UUID] = mapped_column(ForeignKey("users.id"), primary_key=True)
    permissions: Mapped[list[str]] = mapped_column(JSONB, nullable=False)
